<?php

namespace App\Services\OrganizerReports\Generators;

use App\Models\Artist;
use App\Models\User;
use App\Services\OrganizerReports\Contracts\ReportGenerator;
use App\Services\Reports\Concerns\ExportsTabularReport;
use Illuminate\Database\Eloquent\Builder;
use Symfony\Component\HttpFoundation\Response;

class ArtistsReport implements ReportGenerator
{
    use ExportsTabularReport;

    public function generate(User $user, array $fields, array $filters, string $format): Response
    {
        $query = Artist::query()
            ->withCount(['events', 'artistFollows as followers_count'])
            ->latest();

        $this->applyFilters($query, $filters);

        $records = $query->limit(5000)->get();
        $fieldKeys = $fields !== [] ? $fields : array_keys(config('organizer_reports.reports.artists.fields', []));
        $fieldLabels = config('organizer_reports.reports.artists.fields', []);

        $headers = [];
        foreach ($fieldKeys as $key) {
            $headers[] = $fieldLabels[$key] ?? $key;
        }

        $rows = $records->map(function (Artist $artist) use ($fieldKeys) {
            $values = [
                'id' => $artist->id,
                'name' => $artist->name,
                'email' => $artist->email ?? '—',
                'contact_number' => $artist->contact_number ?? '—',
                'events_count' => (int) ($artist->events_count ?? 0),
                'followers' => (int) ($artist->followers_count ?? 0),
                'is_active' => $artist->is_active ? 'Yes' : 'No',
                'created_at' => $artist->created_at?->format('Y-m-d H:i') ?? '—',
            ];

            return array_map(fn ($key) => $values[$key] ?? '—', $fieldKeys);
        })->all();

        $title = 'Organizer Artists Report';

        if ($format === 'csv') {
            return $this->downloadCsv($title, $headers, $rows, 'organizer-artists');
        }

        return $this->downloadPdfTable($title, $headers, $rows, 'organizer-artists', [
            ['label' => 'Total rows', 'value' => count($rows)],
            ['label' => 'Generated by', 'value' => $this->userDisplayName($user)],
            ...$this->dateRangeSummary($filters, 'Created'),
        ]);
    }

    /**
     * @param  array<string, mixed>  $filters
     */
    private function applyFilters(Builder $query, array $filters): void
    {
        $q = trim((string) ($filters['q'] ?? ''));
        if ($q !== '') {
            $query->where(function (Builder $inner) use ($q) {
                $inner->where('name', 'like', "%{$q}%")
                    ->orWhere('email', 'like', "%{$q}%")
                    ->orWhere('contact_number', 'like', "%{$q}%");
            });
        }

        if (isset($filters['active']) && $filters['active'] !== '') {
            $query->where('is_active', (bool) (int) $filters['active']);
        }

        if (! empty($filters['date_from'])) {
            $query->whereDate('created_at', '>=', $filters['date_from']);
        }

        if (! empty($filters['date_to'])) {
            $query->whereDate('created_at', '<=', $filters['date_to']);
        }
    }
}
