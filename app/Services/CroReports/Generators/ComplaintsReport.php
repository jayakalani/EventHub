<?php

namespace App\Services\CroReports\Generators;

use App\Enums\SupportTicketStatusEnum;
use App\Models\Complaint;
use App\Models\User;
use App\Services\Reports\Concerns\ExportsTabularReport;
use App\Services\CroReports\Contracts\ReportGenerator;
use Illuminate\Database\Eloquent\Builder;
use Symfony\Component\HttpFoundation\Response;

class ComplaintsReport implements ReportGenerator
{
    use ExportsTabularReport;

    public function generate(User $user, array $fields, array $filters, string $format): Response
    {
        $query = Complaint::query()
            ->with(['user:id,first_name,last_name,email', 'assignee:id,first_name,last_name,email'])
            ->forCroQueue((int) $user->id)
            ->latest();

        $this->applyFilters($query, $filters, (int) $user->id);

        $records = $query->limit(5000)->get();
        $fieldKeys = $fields !== [] ? $fields : array_keys(config('cro_reports.reports.complaints.fields', []));
        $fieldLabels = config('cro_reports.reports.complaints.fields', []);

        $headers = [];
        foreach ($fieldKeys as $key) {
            $headers[] = $fieldLabels[$key] ?? $key;
        }

        $rows = $records->map(function (Complaint $complaint) use ($fieldKeys) {
            $values = [
                'id' => $complaint->id,
                'subject' => $complaint->subject,
                'user' => $this->userDisplayName($complaint->user),
                'status' => $complaint->status instanceof SupportTicketStatusEnum
                    ? $complaint->status->label()
                    : (string) $complaint->status,
                'assignee' => $this->userDisplayName($complaint->assignee),
                'submitted_at' => optional($complaint->created_at)?->format('Y-m-d H:i') ?? '—',
                'updated_at' => optional($complaint->updated_at)?->format('Y-m-d H:i') ?? '—',
            ];

            return array_map(fn ($key) => $values[$key] ?? '—', $fieldKeys);
        })->all();

        $title = 'CRO Complaints Report';

        if ($format === 'csv') {
            return $this->downloadCsv($title, $headers, $rows, 'cro-complaints');
        }

        return $this->downloadPdfTable($title, $headers, $rows, 'cro-complaints', [
            ['label' => 'Total rows', 'value' => count($rows)],
            ['label' => 'Generated by', 'value' => $this->userDisplayName($user)],
        ]);
    }

    /**
     * @param  array<string, mixed>  $filters
     */
    private function applyFilters(Builder $query, array $filters, int $croId): void
    {
        $q = trim((string) ($filters['q'] ?? ''));
        if ($q !== '') {
            $query->where(function (Builder $inner) use ($q) {
                $inner->where('subject', 'like', "%{$q}%")
                    ->orWhere('message', 'like', "%{$q}%")
                    ->orWhereHas('user', function (Builder $user) use ($q) {
                        $user->where('first_name', 'like', "%{$q}%")
                            ->orWhere('last_name', 'like', "%{$q}%")
                            ->orWhere('email', 'like', "%{$q}%");
                    });
            });
        }

        if (! empty($filters['status'])) {
            $query->where('status', $filters['status']);
        }

        $assignment = (string) ($filters['assignment'] ?? 'all');
        if (in_array($assignment, ['me', 'unassigned'], true)) {
            $query->assignmentFilter($assignment, $croId);
        }

        if (! empty($filters['date_from'])) {
            $query->whereDate('created_at', '>=', $filters['date_from']);
        }

        if (! empty($filters['date_to'])) {
            $query->whereDate('created_at', '<=', $filters['date_to']);
        }
    }
}
